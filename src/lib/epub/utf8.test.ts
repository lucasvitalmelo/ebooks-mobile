test.each(invalid)('decodifica bytes inválidos %#  como o TextDecoder', (...bytes) => {
  const input = Uint8Array.from(bytes)
  expect(decodeUtf8(input)).toBe(new TextDecoder().decode(input))
})

test('decodifica todo par de bytes como o TextDecoder', () => {
  const decoder = new TextDecoder()
  for (let a = 0; a < 256; a++) {
    for (const b of [0x00, 0x41, 0x7f, 0x80, 0x8f, 0x90, 0x9f, 0xa0, 0xbf, 0xc0, 0xff]) {
      for (const c of [0x80, 0xa0, 0xbf, 0x41]) {
        const input = Uint8Array.from([a, b, c])
        expect(decodeUtf8(input)).toBe(decoder.decode(input))
      }
    }
  }
})
